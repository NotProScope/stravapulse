"""Download picked Commons photos into the app and write js/photos.js with credits.
usage: python3 -I photos_pick.py <candidates.json> <app_dir>
"""
import json, subprocess, sys, pathlib, time

cands = json.load(open(sys.argv[1]))
app = pathlib.Path(sys.argv[2])
(app / 'photos').mkdir(exist_ok=True)
UA = 'pulse-demo-photo-finder/1.0 (student case-competition prototype)'

PICKS = {  # app key: (search key, index)
    'drake': ('t1', 0), 'drake_meet': ('t1', 2), 'smc': ('t2', 0), 'venicehs': ('t3', 0), 'unihigh': ('t4', 3),
    'culverhs': ('t5', 3), 'westwood': ('westwood', 0), 'pier': ('pier', 0), 'venice': ('venice', 4),
    'ballona': ('ballona', 0), 'overlook': ('overlook', 0), 'ucla': ('ucla', 1), 'sanvicente': ('sanvicente', 5),
}
out = {}
for key, (place, idx) in PICKS.items():
    c = cands[place][idx]
    dest = app / 'photos' / f'{key}.jpg'
    for attempt in range(4):
        subprocess.run(['curl', '-s', '-L', '-m', '60', '-A', UA, '-o', str(dest), c['thumb']], check=False)
        if dest.exists() and dest.stat().st_size > 20000 and dest.read_bytes()[:2] in (b'\xff\xd8', b'\x89P'):
            break
        time.sleep(3 + attempt * 3)
    out[key] = {'src': f'photos/{key}.jpg', 'title': c['title'][5:], 'artist': c['artist'] or 'Unknown', 'license': c['license'],
                'licenseUrl': c['licenseUrl'], 'page': c['page']}
    print(key, dest.stat().st_size if dest.exists() else 'MISSING', c['license'], c['artist'][:40])
    time.sleep(1)
(app / 'js' / 'photos.js').write_text(
    '/* Photos from Wikimedia Commons under open licenses (credited on screen and below).\n'
    '   Generated by tools/photos_pick.py. */\n'
    'const PHOTOS = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
